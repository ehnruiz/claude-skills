import importlib.util
import json
import pathlib
import subprocess
import sys
import tempfile
import unittest

ROOT = pathlib.Path(__file__).resolve().parents[1]
HOOK = ROOT / "hooks" / "prose_lint.py"
SPEC = importlib.util.spec_from_file_location("prose_lint", HOOK)
hook = importlib.util.module_from_spec(SPEC)
SPEC.loader.exec_module(hook)

CURLY = "it’s done"
DASH = "done — mostly"


def kinds(text):
    return [kind for kind, _ in hook.findings(text)]


def run(event=None, raw=None):
    data = raw if raw is not None else json.dumps(event)
    return subprocess.run([sys.executable, str(HOOK)], input=data, capture_output=True, text=True, timeout=20)


def assistant(*blocks):
    return json.dumps({"type": "assistant", "message": {"role": "assistant", "content": list(blocks)}})


def text_block(text):
    return {"type": "text", "text": text}


def user(text):
    return json.dumps({"type": "user", "message": {"role": "user", "content": text}})


class FindingsTest(unittest.TestCase):
    def test_curly_quote(self):
        self.assertEqual(kinds(CURLY), ["curly quote"])
        self.assertEqual(kinds("it's done"), [])

    def test_em_dash(self):
        self.assertEqual(kinds(DASH), ["em dash"])
        self.assertEqual(kinds("done - mostly, 2020-2021 and en–dash"), [])

    def test_british_spelling(self):
        for word in ["colour", "Favourite", "organised", "analyse", "analysing", "centre", "whilst", "cheques"]:
            self.assertEqual(kinds(f"the {word} here"), ["British spelling"], word)

    def test_american_text_is_clean(self):
        text = "The analyses show the license for the program, in color. See https://example.com/colour/centre."
        self.assertEqual(hook.findings(text), [])

    def test_ai_attribution(self):
        for text in [
            "Generated with Claude Code",
            "generated by Claude",
            "Co-Authored-By: Claude <noreply@anthropic.com>",
            "https://claude.ai/code/session_abc",
            "Claude-Session: abc",
            "\U0001F916 Generated with a tool",
        ]:
            self.assertIn("AI attribution", kinds(text), text)

    def test_no_attribution_when_claude_is_just_mentioned(self):
        self.assertEqual(kinds("Claude reviewed the diff and the team merged it."), [])

    def test_excerpt_is_capped_and_single_line(self):
        text = "a" * 30 + "\n" + "colour" + "\n" + "b" * 30
        (_, excerpt), = hook.findings(text)
        self.assertLessEqual(len(excerpt), 40)
        self.assertNotIn("\n", excerpt)
        self.assertIn("colour", excerpt)


class BashModeTest(unittest.TestCase):
    def bash(self, command):
        return run({"hook_event_name": "PreToolUse", "tool_name": "Bash", "tool_input": {"command": command}})

    def test_git_commit_with_curly_apostrophe_asks(self):
        result = self.bash(f"git commit -m \"it’s fixed\"")
        self.assertEqual(result.returncode, 0)
        out = json.loads(result.stdout)["hookSpecificOutput"]
        self.assertEqual(out["hookEventName"], "PreToolUse")
        self.assertEqual(out["permissionDecision"], "ask")
        reason = out["permissionDecisionReason"]
        self.assertIn('curly quote: "', reason)
        self.assertTrue(reason.endswith("no AI attribution."))

    def test_gh_pr_create_with_attribution_asks(self):
        result = self.bash('gh pr create --title t --body "Generated with Claude Code"')
        out = json.loads(result.stdout)["hookSpecificOutput"]
        self.assertEqual(out["permissionDecision"], "ask")
        self.assertIn("AI attribution", out["permissionDecisionReason"])

    def test_clean_commit_prints_nothing(self):
        result = self.bash('git commit -m "Fix the color picker"')
        self.assertEqual((result.returncode, result.stdout), (0, ""))

    def test_other_command_with_curly_quote_prints_nothing(self):
        result = self.bash("ls -la “folder”")
        self.assertEqual((result.returncode, result.stdout), (0, ""))

    def test_non_bash_tool_prints_nothing(self):
        result = run({"hook_event_name": "PreToolUse", "tool_name": "Edit", "tool_input": {"command": "git commit —"}})
        self.assertEqual((result.returncode, result.stdout), (0, ""))


class StopModeTest(unittest.TestCase):
    def setUp(self):
        self.tmp = pathlib.Path(tempfile.mkdtemp())

    def transcript(self, *lines):
        path = self.tmp / "t.jsonl"
        path.write_text("\n".join(lines) + "\n")
        return str(path)

    def stop(self, path=None, **extra):
        event = {"hook_event_name": "Stop", **extra}
        if path:
            event["transcript_path"] = path
        return run(event)

    def test_em_dash_in_final_message_exits_2(self):
        path = self.transcript(user("hi"), assistant(text_block(DASH)))
        result = self.stop(path)
        self.assertEqual(result.returncode, 2)
        self.assertIn("em dash", result.stderr)
        self.assertIn("Fix these in your final message before finishing.", result.stderr)

    def test_stop_hook_active_adds_context_and_exits_0(self):
        path = self.transcript(assistant(text_block(DASH)))
        result = self.stop(path, stop_hook_active=True)
        self.assertEqual(result.returncode, 0)
        out = json.loads(result.stdout)["hookSpecificOutput"]
        self.assertEqual(out["hookEventName"], "Stop")
        self.assertEqual(out["additionalContext"], "prose-lint still sees: em dash")

    def test_clean_final_message_exits_0_silently(self):
        result = self.stop(self.transcript(assistant(text_block("All done."))))
        self.assertEqual((result.returncode, result.stdout, result.stderr), (0, "", ""))

    def test_uses_last_assistant_line_that_has_text(self):
        tool_only = assistant({"type": "tool_use", "id": "x", "name": "Bash", "input": {}})
        path = self.transcript(assistant(text_block(DASH)), tool_only)
        self.assertEqual(self.stop(path).returncode, 2)

    def test_earlier_dash_is_ignored_when_the_last_text_is_clean(self):
        path = self.transcript(assistant(text_block(DASH)), user("ok"), assistant(text_block("Fixed.")))
        self.assertEqual(self.stop(path).returncode, 0)

    def test_joins_all_text_blocks_of_the_line(self):
        block = {"type": "tool_use", "id": "x", "name": "Bash", "input": {}}
        path = self.transcript(assistant(text_block("fine"), block, text_block(DASH)))
        self.assertEqual(self.stop(path).returncode, 2)

    def test_scratchpad_path_exits_2(self):
        for p in ["/private/tmp/claude-502/x/out.md", "/tmp/claude-502/x/out.md"]:
            result = self.stop(self.transcript(assistant(text_block(f"See {p}"))))
            self.assertEqual(result.returncode, 2, p)
            self.assertIn("path the user cannot open", result.stderr)

    def test_ordinary_tmp_path_is_fine(self):
        result = self.stop(self.transcript(assistant(text_block("See /tmp/build/out.txt"))))
        self.assertEqual(result.returncode, 0)

    def test_no_transcript_path_exits_0(self):
        self.assertEqual(self.stop().returncode, 0)

    def test_unreadable_transcript_exits_0(self):
        self.assertEqual(self.stop(str(self.tmp / "missing.jsonl")).returncode, 0)

    def test_garbage_lines_in_the_transcript_are_skipped(self):
        path = self.transcript("not json", assistant(text_block(DASH)))
        self.assertEqual(self.stop(path).returncode, 2)


class MalformedEventTest(unittest.TestCase):
    def test_empty_stdin_allows(self):
        result = run(raw="")
        self.assertEqual((result.returncode, result.stdout), (0, ""))

    def test_malformed_json_allows(self):
        result = run(raw="{not json")
        self.assertEqual((result.returncode, result.stdout), (0, ""))

    def test_non_object_json_allows(self):
        result = run(raw="[1, 2]")
        self.assertEqual((result.returncode, result.stdout), (0, ""))


if __name__ == "__main__":
    unittest.main()
